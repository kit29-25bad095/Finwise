import uuid
from decimal import Decimal
from typing import Optional, List, Dict, Any
from sqlalchemy.orm import Session
from sqlalchemy import select, and_, func

from app.models.forensic import (
    ForensicInvestigation,
    ForensicClaimDraft,
    InvestigationStatus,
    ClaimDraftStatus,
    ClaimDraftReviewStatus,
)
from app.models.leakage import LeakageException
from app.services.forensics.exceptions import (
    ResourceNotFoundError,
    InvalidInvestigationStateError,
    TenantMismatchError,
)


class ClaimDraftService:
    """
    Constructs controlled, human-reviewable dispute claim drafts grounded strictly in
    verified investigation facts and deterministic financial amounts.
    Never submits claims or modifies financial lifecycle state.
    """

    DEFAULT_DISCLAIMER = (
        "DRAFT — HUMAN REVIEW REQUIRED. This claim draft was automatically generated by "
        "Finora AI Forensic Investigator for human evaluation. It does not constitute financial "
        "authorization or an automated dispute submission."
    )

    @classmethod
    def create_claim_draft(
        cls,
        db: Session,
        tenant_id: uuid.UUID,
        investigation_id: uuid.UUID,
        user_id: Optional[uuid.UUID] = None,
        target_entity: Optional[str] = None,
        notes: Optional[str] = None,
    ) -> ForensicClaimDraft:
        """
        Creates a new draft dispute claim strictly referencing deterministic amounts and verified facts.
        """
        # 1. Fetch Investigation with Tenancy Enforcement
        stmt_inv = select(ForensicInvestigation).where(
            and_(
                ForensicInvestigation.id == investigation_id,
                ForensicInvestigation.tenant_id == tenant_id
            )
        )
        inv = db.execute(stmt_inv).scalar_one_or_none()
        if not inv:
            raise ResourceNotFoundError(f"Forensic investigation {investigation_id} not found.")

        if inv.status != InvestigationStatus.COMPLETED.value:
            raise InvalidInvestigationStateError(
                f"Cannot generate a claim draft for investigation {investigation_id} with status '{inv.status}'. "
                "Investigation must be COMPLETED."
            )

        # 2. Fetch Exception with Tenancy Enforcement
        stmt_exc = select(LeakageException).where(
            and_(
                LeakageException.id == inv.exception_id,
                LeakageException.tenant_id == tenant_id
            )
        )
        exc = db.execute(stmt_exc).scalar_one_or_none()
        if not exc:
            raise ResourceNotFoundError(f"Leakage exception {inv.exception_id} not found.")

        # 3. Deterministic Financial Quantum (Strict Zero-AI-Calculation rule)
        # Dispute amount is taken directly from the verified leakage or recoverable amount
        dispute_amount = (
            exc.recoverable_amount if exc.recoverable_amount > Decimal("0.0000") else exc.leakage_amount
        )
        currency = exc.currency

        # Target Entity & Reference
        resolved_target = (
            target_entity.strip() if target_entity and target_entity.strip() else exc.gateway_name
        )
        target_ref = exc.source_reference

        # 4. Extract Verified Facts and Evidence References from Investigation Bundle
        inv_result = inv.investigation_result or {}
        verified_facts = inv_result.get("verified_facts", [])
        if not verified_facts:
            verified_facts = [
                f"Exception type: {exc.exception_type}",
                f"Source reference: {exc.source_reference}",
                f"Disputed amount: {currency} {dispute_amount:.4f}",
            ]

        bundle_snapshot = inv.evidence_bundle_snapshot or {}
        evidence_items = bundle_snapshot.get("evidence_items", [])
        evidence_refs: List[Dict[str, Any]] = [
            {
                "evidence_id": item.get("evidence_id"),
                "fingerprint_sha256": item.get("fingerprint_sha256"),
                "evidence_type": item.get("evidence_type"),
                "verification_status": item.get("verification_status"),
            }
            for item in evidence_items
            if item.get("verification_status") == "VERIFIED"
        ]

        unresolved_questions = inv_result.get("missing_information", [])
        recommended_attachments = [
            f"Ingestion batch source records for {resolved_target}",
            f"Settlement advice reference: {target_ref}",
            "Bank statement clearing confirmation",
        ]

        # 5. Formulate Claim Summary
        claim_summary = (
            f"Formal dispute claim for {exc.detector_type} ({exc.exception_type}) regarding "
            f"reference {target_ref} against {resolved_target}. Disputed quantum: {currency} {dispute_amount:.4f}."
        )
        if notes:
            claim_summary += f" Reviewer notes: {notes.strip()}"

        # 6. Compute draft version number
        stmt_count = select(func.count(ForensicClaimDraft.id)).where(
            and_(
                ForensicClaimDraft.tenant_id == tenant_id,
                ForensicClaimDraft.exception_id == exc.id
            )
        )
        existing_drafts_count = db.execute(stmt_count).scalar() or 0
        draft_number = existing_drafts_count + 1

        # 7. Create Draft
        draft = ForensicClaimDraft(
            tenant_id=tenant_id,
            exception_id=exc.id,
            investigation_id=inv.id,
            detection_run_id=inv.detection_run_id,
            draft_number=draft_number,
            status=ClaimDraftStatus.DRAFT.value,
            dispute_amount=dispute_amount,
            currency=currency,
            target_entity=resolved_target,
            target_reference=target_ref,
            claim_summary=claim_summary,
            supporting_facts=verified_facts,
            evidence_references=evidence_refs,
            unresolved_questions=unresolved_questions,
            required_attachments=recommended_attachments,
            human_review_status=ClaimDraftReviewStatus.PENDING_HUMAN_REVIEW.value,
            disclaimer=cls.DEFAULT_DISCLAIMER,
            created_by_user_id=user_id,
        )

        db.add(draft)
        db.commit()
        db.refresh(draft)
        return draft

    @classmethod
    def get_claim_draft(
        cls,
        db: Session,
        tenant_id: uuid.UUID,
        draft_id: uuid.UUID
    ) -> ForensicClaimDraft:
        """
        Retrieves a claim draft with strict tenant isolation.
        """
        stmt = select(ForensicClaimDraft).where(
            and_(
                ForensicClaimDraft.id == draft_id,
                ForensicClaimDraft.tenant_id == tenant_id
            )
        )
        draft = db.execute(stmt).scalar_one_or_none()
        if not draft:
            raise ResourceNotFoundError(f"Claim draft {draft_id} not found.")
        return draft
